UPGRADE_SQL = f"""
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE SCHEMA IF NOT EXISTS catalog;

-- The single normalization algorithm used for every uniqueness rule and name lookup:
-- NFKC (full-width -> ASCII), unaccent (Câmera -> Camera, Ø -> O, ß -> ss), lower case,
-- then drop everything that is not a latin letter or digit ("Amazon Basics" -> "amazonbasics").
-- unaccent() itself is only STABLE; pinning the dictionary makes the wrapper safe to declare
-- IMMUTABLE (REINDEX the key indexes if the unaccent rules file is ever changed).
CREATE FUNCTION catalog.name_key(t text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    RETURN regexp_replace(
        lower(public.unaccent('public.unaccent'::regdictionary, normalize(t, NFKC))),
        '[^a-z0-9]', '', 'g');

-- Word-preserving variant, only used for "looks similar" suggestions (pg_trgm).
CREATE FUNCTION catalog.name_fold(t text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
    RETURN btrim(regexp_replace(
        lower(public.unaccent('public.unaccent'::regdictionary, normalize(t, NFKC))),
        '[^a-z0-9]+', ' ', 'g'));

CREATE FUNCTION catalog.set_updated() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated := now();
    RETURN NEW;
END
$$;

CREATE TABLE catalog.seller (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    {TIMESTAMPS},
    CONSTRAINT seller_name_key_not_empty CHECK (catalog.name_key(name) <> '')
);

CREATE TABLE catalog.brand (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    merged_into_id bigint REFERENCES catalog.brand (id) ON DELETE RESTRICT,
    {TIMESTAMPS},
    CONSTRAINT brand_name_key_not_empty CHECK (catalog.name_key(name) <> ''),
    CONSTRAINT brand_not_merged_into_self CHECK (merged_into_id <> id)
);

CREATE TABLE catalog.category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    merged_into_id bigint REFERENCES catalog.category (id) ON DELETE RESTRICT,
    {TIMESTAMPS},
    CONSTRAINT category_name_key_not_empty CHECK (catalog.name_key(name) <> ''),
    CONSTRAINT category_name_lowercase CHECK (name = lower(name)),
    CONSTRAINT category_not_merged_into_self CHECK (merged_into_id <> id)
);

CREATE TABLE catalog.product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid uuid NOT NULL DEFAULT uuidv7(),
    name text NOT NULL,
    brand_id bigint REFERENCES catalog.brand (id) ON DELETE RESTRICT,
    active boolean NOT NULL DEFAULT true,
    merged_into_id bigint REFERENCES catalog.product (id) ON DELETE RESTRICT,
    {TIMESTAMPS},
    CONSTRAINT product_uuid_unique UNIQUE (uuid),
    -- uuid_extract_version() is NULL for non-RFC variants and a NULL CHECK passes, so the
    -- comparison must be NULL-safe.
    CONSTRAINT product_uuid_is_v7 CHECK (uuid_extract_version(uuid) IS NOT DISTINCT FROM 7),
    CONSTRAINT product_name_key_not_empty CHECK (catalog.name_key(name) <> ''),
    CONSTRAINT product_not_merged_into_self CHECK (merged_into_id <> id)
);

CREATE TABLE catalog.product_category (
    product_id bigint NOT NULL REFERENCES catalog.product (id) ON DELETE RESTRICT,
    category_id bigint NOT NULL REFERENCES catalog.category (id) ON DELETE RESTRICT,
    active boolean NOT NULL DEFAULT true,
    {TIMESTAMPS},
    PRIMARY KEY (product_id, category_id)
);

CREATE TABLE catalog.operation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('legacy_load', 'import', 'merge', 'undo')),
    status text NOT NULL CHECK (status IN (
        'running', 'completed', 'failed',
        'undone', 'partially_undone', 'reverted', 'partially_reverted')),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    error_message text,
    summary jsonb,
    {TIMESTAMPS}
);

CREATE TABLE catalog.seller_product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id bigint NOT NULL REFERENCES catalog.seller (id) ON DELETE RESTRICT,
    product_id bigint NOT NULL REFERENCES catalog.product (id) ON DELETE RESTRICT,
    seller_product_id uuid NOT NULL,
    name text NOT NULL,
    brand_name text,
    category_name text,
    active boolean NOT NULL DEFAULT true,
    last_operation_id bigint REFERENCES catalog.operation (id) ON DELETE RESTRICT,
    {TIMESTAMPS},
    CONSTRAINT seller_product_seller_key UNIQUE (seller_id, seller_product_id),
    CONSTRAINT seller_product_one_offer_per_product UNIQUE (seller_id, product_id)
);

CREATE TABLE catalog.import_batch (
    operation_id bigint PRIMARY KEY REFERENCES catalog.operation (id) ON DELETE RESTRICT,
    file_name text NOT NULL,
    file_path text,
    md5 char(32) NOT NULL CHECK (md5 ~ '^[0-9a-f]{{32}}$'),
    file_size bigint NOT NULL CHECK (file_size >= 0),
    id_validation text NOT NULL,
    total_records integer NOT NULL DEFAULT 0,
    invalid_records integer NOT NULL DEFAULT 0,
    skipped_records integer NOT NULL DEFAULT 0,
    sellers_created integer NOT NULL DEFAULT 0,
    products_created integer NOT NULL DEFAULT 0,
    products_updated integer NOT NULL DEFAULT 0,
    duplicate_products integer NOT NULL DEFAULT 0,
    offers_created integer NOT NULL DEFAULT 0,
    offers_updated integer NOT NULL DEFAULT 0,
    unchanged integer NOT NULL DEFAULT 0,
    {TIMESTAMPS}
);

CREATE TABLE catalog.merge_detail (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL REFERENCES catalog.operation (id) ON DELETE RESTRICT,
    entity_type text NOT NULL CHECK (entity_type IN ('product', 'brand', 'category')),
    kept_id bigint NOT NULL,
    merged_id bigint,
    merged_name text,
    origin text NOT NULL CHECK (origin IN ('legacy_load', 'manual')),
    {TIMESTAMPS},
    CONSTRAINT merge_detail_has_source CHECK (merged_id IS NOT NULL OR merged_name IS NOT NULL)
);

CREATE TABLE catalog.undo_detail (
    operation_id bigint PRIMARY KEY REFERENCES catalog.operation (id) ON DELETE RESTRICT,
    undo_kind text NOT NULL CHECK (undo_kind IN ('import_undo', 'merge_undo', 'revert')),
    criteria jsonb NOT NULL,
    changes_reverted integer NOT NULL DEFAULT 0,
    conflicts_skipped integer NOT NULL DEFAULT 0,
    {TIMESTAMPS}
);

CREATE TABLE catalog.change_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL REFERENCES catalog.operation (id) ON DELETE RESTRICT,
    seller_id bigint REFERENCES catalog.seller (id) ON DELETE RESTRICT,
    table_name text NOT NULL CHECK (table_name IN (
        'seller', 'brand', 'category', 'product', 'product_category', 'seller_product')),
    row_pk jsonb NOT NULL,
    action text NOT NULL CHECK (action IN ('insert', 'update')),
    old_values jsonb,
    new_values jsonb NOT NULL,
    reverts_change_id bigint REFERENCES catalog.change_log (id) ON DELETE RESTRICT,
    reverted_by_operation_id bigint REFERENCES catalog.operation (id) ON DELETE RESTRICT,
    {TIMESTAMPS}
);

-- Uniqueness through the key function: no stored key column that could drift.
CREATE UNIQUE INDEX seller_name_key_uq ON catalog.seller (catalog.name_key(name));
CREATE UNIQUE INDEX brand_name_key_uq ON catalog.brand (catalog.name_key(name));
CREATE UNIQUE INDEX category_name_key_uq ON catalog.category (catalog.name_key(name));
CREATE UNIQUE INDEX product_name_key_brand_uq
    ON catalog.product (catalog.name_key(name), brand_id) NULLS NOT DISTINCT;

-- Near-duplicate search.
CREATE INDEX brand_name_trgm ON catalog.brand
    USING gin (catalog.name_fold(name) public.gin_trgm_ops);
CREATE INDEX category_name_trgm ON catalog.category
    USING gin (catalog.name_fold(name) public.gin_trgm_ops);
CREATE INDEX product_name_trgm ON catalog.product
    USING gin (catalog.name_fold(name) public.gin_trgm_ops);

-- Listing / filtering.
CREATE INDEX product_brand_active_ix ON catalog.product (brand_id) WHERE active;
CREATE INDEX product_category_category_ix
    ON catalog.product_category (category_id, product_id) WHERE active;
CREATE INDEX seller_product_product_ix
    ON catalog.seller_product (product_id, seller_id) WHERE active;

-- Operations and change log.
CREATE INDEX import_batch_md5_ix ON catalog.import_batch (md5);
CREATE INDEX operation_kind_started_ix ON catalog.operation (kind, started_at);
CREATE INDEX merge_detail_operation_ix ON catalog.merge_detail (operation_id);
CREATE INDEX change_log_operation_ix ON catalog.change_log (operation_id);
CREATE INDEX change_log_seller_created_ix ON catalog.change_log (seller_id, created);
CREATE INDEX change_log_row_ix ON catalog.change_log (table_name, row_pk);
CREATE INDEX change_log_reverted_by_ix ON catalog.change_log (reverted_by_operation_id);
CREATE INDEX change_log_reverts_ix ON catalog.change_log (reverts_change_id);
"""


def upgrade() -> None:
    op.execute(UPGRADE_SQL)
    for table in TABLES_WITH_UPDATED:
        op.execute(
            f"CREATE TRIGGER {table}_set_updated BEFORE UPDATE ON catalog.{table} "
            "FOR EACH ROW EXECUTE FUNCTION catalog.set_updated()"
        )
    # Read-only role used by the API (created by docker/postgres/initdb). Optional so the
    # schema can also be created on a server without that role.
    op.execute(
        f"""
        DO $$
        BEGIN
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{READER_ROLE}') THEN
                GRANT USAGE ON SCHEMA catalog TO {READER_ROLE};
                GRANT SELECT ON ALL TABLES IN SCHEMA catalog TO {READER_ROLE};
                ALTER DEFAULT PRIVILEGES IN SCHEMA catalog GRANT SELECT ON TABLES TO {READER_ROLE};
                GRANT SELECT ON public.alembic_version TO {READER_ROLE};
            END IF;
        END
        $$;
        """
    )


def downgrade() -> None:
    op.execute("DROP SCHEMA catalog CASCADE")
